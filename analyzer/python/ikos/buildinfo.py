"""Build identity embedded in the native analyzer, plus local freshness checks."""
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import subprocess


SOURCE_DIRS = (
    'core/include', 'ar/include', 'ar/src', 'frontend/llvm/include',
    'frontend/llvm/src', 'analyzer/include', 'analyzer/src', 'analyzer/python',
    'analyzer/script', 'cmake',
)
SOURCE_FILES = (
    'CMakeLists.txt', 'core/CMakeLists.txt', 'ar/CMakeLists.txt',
    'frontend/llvm/CMakeLists.txt', 'analyzer/CMakeLists.txt', 'DEV_VERSION',
)
SOURCE_SUFFIXES = {'.h', '.hpp', '.c', '.cpp', '.py', '.in', '.cmake'}


def source_digest(root):
    root = Path(root)
    if not (root / 'DEV_VERSION').is_file():
        raise FileNotFoundError('DEV_VERSION/source tree not found')
    files = {root / name for name in SOURCE_FILES if (root / name).is_file()}
    for name in SOURCE_DIRS:
        folder = root / name
        if folder.is_dir():
            files.update(p for p in folder.rglob('*')
                         if p.is_file() and p.suffix in SOURCE_SUFFIXES)
    digest = hashlib.sha256()
    for path in sorted(files, key=lambda p: p.relative_to(root).as_posix()):
        digest.update(path.relative_to(root).as_posix().encode('utf-8'))
        digest.update(b'\0')
        digest.update(path.read_bytes())
        digest.update(b'\0')
    return digest.hexdigest()


def file_digest(path):
    digest = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b''):
            digest.update(chunk)
    return digest.hexdigest()


def git_identity(root):
    def git(*args):
        try:
            result = subprocess.run(['git', '-C', str(root), *args],
                                    stdout=subprocess.PIPE,
                                    stderr=subprocess.DEVNULL, text=True)
            return result.stdout.strip() if result.returncode == 0 else None
        except OSError:
            return None
    revision = git('rev-parse', 'HEAD')
    status = git('status', '--porcelain', '--untracked-files=all', '--',
                 *SOURCE_DIRS, *SOURCE_FILES)
    return revision or 'unknown', bool(status) if status is not None else None


def write_if_changed(path, text):
    path = Path(path)
    if path.is_file() and path.read_text() == text:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + '.tmp')
    temporary.write_text(text)
    temporary.replace(path)


def generate(opts):
    root = opts.source_root.resolve()
    version = (root / 'DEV_VERSION').read_text().strip()
    if not re.fullmatch(r'[0-9]+\.[0-9]+\.[0-9]+(?:[-+][A-Za-z0-9.-]+)?', version):
        raise ValueError('DEV_VERSION must contain a version such as 0.1.0')
    revision, dirty = git_identity(root)
    info = dict(schema=1, dev_version=version, upstream_version=opts.upstream,
                git_revision=revision, git_dirty=dirty,
                source_sha256=source_digest(root), source_root=str(root),
                build_mode=opts.build_mode, compiler=opts.compiler,
                build_flags=opts.build_flags, llvm_version=opts.llvm_version,
                features=opts.features, build_binary=str(opts.build_binary.resolve()))
    info['build_id'] = hashlib.sha256(
        json.dumps(info, sort_keys=True).encode('utf-8')).hexdigest()[:16]
    sidecar = opts.output.with_suffix('.json')
    try:
        previous = json.loads(sidecar.read_text())
    except (OSError, ValueError):
        previous = {}
    # Preserve the timestamp/content on a no-op build; do not force relinking.
    info['built_utc'] = previous.get('built_utc') if previous.get('build_id') == info['build_id'] else None
    if not info['built_utc']:
        info['built_utc'] = datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')
    dirty_suffix = '-dirty' if dirty else ''
    banner = ('ikos-dev {dev_version} (IKOS {upstream_version})\n'
              'Build ID: {build_id}\nGit: {revision}{dirty}\n'
              'Source SHA256: {source_sha256}\nBuilt UTC: {built_utc}\n'
              'Build mode: {build_mode}\n').format(
                  **info, revision=revision[:12], dirty=dirty_suffix)
    payload = json.dumps(info, sort_keys=True)
    cpp = ('// Generated by ikos/buildinfo.py. Do not edit.\n'
           '#include <ikos/analyzer/util/build_info.hpp>\n'
           'namespace ikos { namespace analyzer {\n'
           'const char* build_info_json() { return ' + json.dumps(payload) + '; }\n'
           'const char* build_version_banner() { return ' + json.dumps(banner) + '; }\n'
           '} }\n')
    write_if_changed(opts.output, cpp)
    write_if_changed(sidecar, json.dumps(info, sort_keys=True, indent=2) + '\n')


def analyzer_info(analyzer):
    result = subprocess.run([str(analyzer), '--build-info'],
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                            text=True, timeout=10, check=True)
    info = json.loads(result.stdout)
    if info.get('schema') != 1:
        raise ValueError('unsupported analyzer build-info schema')
    return info


def version_lines(analyzer):
    # Read the native executable's snapshot, never live Git as its version.
    analyzer = Path(analyzer).resolve()
    info = analyzer_info(analyzer)
    lines = [f'ikos-dev {info["dev_version"]} (IKOS {info["upstream_version"]})',
             f'Build ID: {info["build_id"]}',
             'Git: ' + info['git_revision'][:12] + ('-dirty' if info['git_dirty'] else ''),
             f'Built UTC: {info["built_utc"]}',
             f'Build mode: {info["build_mode"]}',
             f'Source SHA256: {info["source_sha256"]}',
             f'Analyzer: {analyzer}']
    try:
        matches = source_digest(info['source_root']) == info['source_sha256']
        lines.append('Source check: ' + ('MATCH' if matches else
                     'STALE - sources changed; rebuild and install'))
    except OSError:
        lines.append('Source check: unavailable (source tree not accessible)')
    try:
        matches = file_digest(analyzer) == file_digest(info['build_binary'])
        lines.append('Install check: ' + ('MATCH' if matches else
                     'STALE - installed analyzer differs from build; run ninja install'))
    except OSError:
        lines.append('Install check: unavailable (build binary not accessible)')
    return lines


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--source-root', type=Path, required=True)
    parser.add_argument('--build-binary', type=Path, required=True)
    parser.add_argument('--upstream', required=True)
    parser.add_argument('--build-mode', required=True)
    parser.add_argument('--compiler', required=True)
    parser.add_argument('--build-flags', default='')
    parser.add_argument('--llvm-version', required=True)
    parser.add_argument('--features', default='')
    generate(parser.parse_args())


if __name__ == '__main__':
    main()
